-- 1. 创建预准许住院号白名单表
CREATE TABLE IF NOT EXISTS public.inpatient_whitelist (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inpatient_id TEXT NOT NULL UNIQUE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. 创建住院号准入申请与审批队列表
CREATE TABLE IF NOT EXISTS public.inpatient_requests (
  id TEXT PRIMARY KEY,
  inpatient_id TEXT NOT NULL UNIQUE,
  note TEXT DEFAULT '',
  time TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending', -- 'pending' | 'approved' | 'rejected'
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. 创建患者病历资料与图片归档表
CREATE TABLE IF NOT EXISTS public.medical_submissions (
  id TEXT PRIMARY KEY,
  inpatient_id TEXT NOT NULL,
  record_time TEXT NOT NULL,
  record_year TEXT DEFAULT '',
  record_month TEXT DEFAULT '',
  record_day TEXT DEFAULT '',
  record_time_note TEXT DEFAULT '',
  category TEXT NOT NULL,
  note TEXT DEFAULT '',
  submitted_at TEXT NOT NULL,
  images JSONB NOT NULL DEFAULT '[]'::jsonb,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. 插入初始测试白名单住院号
INSERT INTO public.inpatient_whitelist (inpatient_id)
VALUES ('ZY2026001'), ('ZY2026002'), ('ZY2026008'), ('20261018')
ON CONFLICT (inpatient_id) DO NOTHING;

-- 5. 开启行级安全策略 (RLS) 并配置读写策略
ALTER TABLE public.inpatient_whitelist ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inpatient_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.medical_submissions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public access whitelist" ON public.inpatient_whitelist;
CREATE POLICY "Allow public access whitelist" ON public.inpatient_whitelist FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public access requests" ON public.inpatient_requests;
CREATE POLICY "Allow public access requests" ON public.inpatient_requests FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public access submissions" ON public.medical_submissions;
CREATE POLICY "Allow public access submissions" ON public.medical_submissions FOR ALL USING (true) WITH CHECK (true);

-- 6. 创建用于存放病历图片的公开存储桶 (Storage Bucket: medical-images)
INSERT INTO storage.buckets (id, name, public)
VALUES ('medical-images', 'medical-images', true)
ON CONFLICT (id) DO NOTHING;

DROP POLICY IF EXISTS "Allow public upload medical-images" ON storage.objects;
CREATE POLICY "Allow public upload medical-images" ON storage.objects
  FOR INSERT WITH CHECK (bucket_id = 'medical-images');

DROP POLICY IF EXISTS "Allow public read medical-images" ON storage.objects;
CREATE POLICY "Allow public read medical-images" ON storage.objects
  FOR SELECT USING (bucket_id = 'medical-images');

DROP POLICY IF EXISTS "Allow public delete medical-images" ON storage.objects;
CREATE POLICY "Allow public delete medical-images" ON storage.objects
  FOR DELETE USING (bucket_id = 'medical-images');
